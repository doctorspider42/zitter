#!/usr/bin/env python3
"""Compile and embed the lab's Metal library; no runtime shader-source compiler."""
import argparse
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="zitter-metal-") as temporary:
        air = Path(temporary) / "ui.air"
        library = Path(temporary) / "ui.metallib"
        subprocess.run(["xcrun", "--sdk", "macosx", "metal", "-std=metal3.0",
                        "-mmacosx-version-min=13.0", "-c", str(args.source), "-o", str(air)], check=True)
        subprocess.run(["xcrun", "--sdk", "macosx", "metallib", str(air), "-o", str(library)], check=True)
        data = library.read_bytes()
    lines = [", ".join(f"0x{byte:02x}" for byte in data[start:start + 16])
             for start in range(0, len(data), 16)]
    text = ("// Generated by compile_ui_lab_metal.py.\n#pragma once\n"
            "namespace zitter::ui_lab {\ninline constexpr unsigned char kShaderLibrary[] = {\n"
            + ",\n".join(lines) + "\n};\n}\n")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text)


if __name__ == "__main__":
    main()
