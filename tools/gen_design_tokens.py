"""Generates chromium/prototype/design_tokens.rs from docs/design-system/tokens.json.

The design system's tokens.json is the source of truth for every fixed value
(neutral colors, type, spacing, radii, shadows, durations). Workspace colors are
not fixed: chromium/prototype/design.rs derives them, so the accent-* families
in tokens.json are reference renderings and are skipped here.

  tools/gen_design_tokens.py          rewrite the Rust file
  tools/gen_design_tokens.py --check  exit 1 when the Rust file is stale
"""

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs/design-system/tokens.json"
OUTPUT = ROOT / "chromium/prototype/design_tokens.rs"
THEMES = ("dark", "light")
DERIVED = re.compile(r"^(on-)?accent-")


def const_name(name):
    return re.sub(r"[^A-Za-z0-9]+", "_", name).upper()


def argb(value):
    m = re.fullmatch(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?", value)
    if not m:
        raise ValueError(f"unsupported color {value!r}")
    alpha = m.group(2) or "ff"
    return f"0x{alpha}{m.group(1)}".lower()


def resolve_colors(tokens):
    by_name = {t["name"]: t["value"] for t in tokens}

    def value(name, theme, depth=0):
        if depth > 16:
            raise ValueError(f"alias chain too deep at {name}")
        v = by_name[name]
        v = v if isinstance(v, str) else v.get(theme, v[THEMES[0]])
        alias = re.fullmatch(r"\{(.+)\}", v)
        return value(alias.group(1), theme, depth + 1) if alias else v

    return {name: {th: value(name, th) for th in THEMES} for name in by_name}


def px(value):
    if isinstance(value, (int, float)):
        return float(value)
    if value == "0":
        return 0.0
    m = re.fullmatch(r"(-?[0-9.]+)px", value)
    if not m:
        raise ValueError(f"expected px, got {value!r}")
    return float(m.group(1))


def em(value):
    m = re.fullmatch(r"(-?[0-9.]+)em", value)
    if not m:
        raise ValueError(f"expected em, got {value!r}")
    return float(m.group(1))


def ms(value):
    m = re.fullmatch(r"([0-9]+)ms", value)
    if not m:
        raise ValueError(f"expected ms, got {value!r}")
    return int(m.group(1))


def shadow_layers(value):
    layers = []
    for part in value.split(","):
        bits = part.split()
        *lengths, color = bits
        x, y, blur, *spread = (px(b) for b in lengths)
        layers.append((x, y, blur, spread[0] if spread else 0.0, argb(color)))
    return layers


def f(value):
    text = repr(float(value))
    return text if "." in text or "e" in text else text + ".0"


def family_names(stack):
    return [n.strip().strip('"') for n in stack.split(",")]


def render(data):
    out = [
        "// Copyright 2026 Zitter contributors. SPDX-License-Identifier: Apache-2.0",
        "// @generated by tools/gen_design_tokens.py from docs/design-system/tokens.json.",
        "// Do not edit: change tokens.json and rerun the generator.",
        "#![allow(dead_code)]",
        "",
        "/// One ARGB value per theme (Noc = dark, Papier = light).",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Themed { pub dark: u32, pub light: u32 }",
        "",
        "#[derive(Clone, Copy, Debug, PartialEq)]",
        "pub struct ShadowLayer { pub x: f32, pub y: f32, pub blur: f32, pub spread: f32, pub color: u32 }",
        "",
        "#[derive(Clone, Copy, Debug, PartialEq)]",
        "pub struct ThemedShadow { pub dark: &'static [ShadowLayer], pub light: &'static [ShadowLayer] }",
        "",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub enum Family { Display, Sans, Mono }",
        "",
        "/// line_height is in px; letter_spacing in em.",
        "#[derive(Clone, Copy, Debug, PartialEq)]",
        "pub struct TypeStyle { pub family: Family, pub size: f32, pub line_height: f32, pub weight: u16, pub italic: bool, pub letter_spacing: f32 }",
        "",
    ]

    colors = [t for t in data["color"]["tokens"] if not DERIVED.match(t["name"])]
    resolved = resolve_colors(data["color"]["tokens"])
    out.append("pub mod color {")
    out.append("    use super::Themed;")
    for t in colors:
        v = resolved[t["name"]]
        out.append(f"    /// {t['usage']}")
        out.append(f"    pub const {const_name(t['name'])}: Themed = Themed {{ dark: {argb(v['dark'])}, light: {argb(v['light'])} }};")
    out.append("}")
    out.append("")

    out.append("pub mod font {")
    out.append("    use super::Family;")
    for key, stack in data["type"]["families"].items():
        names = ", ".join(json.dumps(n) for n in family_names(stack))
        out.append(f"    pub const {const_name(key)}: &[&str] = &[{names}];")
    out.append("    pub fn stack(family: Family) -> &'static [&'static str] {")
    out.append("        match family { Family::Display => DISPLAY, Family::Sans => SANS, Family::Mono => MONO }")
    out.append("    }")
    out.append("}")
    out.append("")

    families = {"display": "Display", "sans": "Sans", "mono": "Mono"}
    out.append("pub mod text {")
    out.append("    use super::{Family, TypeStyle};")
    for group in data["type"]["groups"]:
        for s in group["styles"]:
            size = px(s["fontSize"])
            lh = s["lineHeight"]
            line = size * lh if isinstance(lh, (int, float)) else px(lh)
            fam = families[s.get("family", group["family"])]
            ls = em(s["letterSpacing"]) if "letterSpacing" in s else 0.0
            italic = "true" if s.get("fontStyle") == "italic" else "false"
            out.append(f"    /// {s['usage']}")
            out.append(
                f"    pub const {const_name(s['name'])}: TypeStyle = TypeStyle {{ family: Family::{fam}, size: {f(size)}, "
                f"line_height: {f(round(line, 2))}, weight: {int(s['fontWeight'])}, italic: {italic}, letter_spacing: {f(ls)} }};")
    out.append("}")
    out.append("")

    for family, unit in (("spacing", "space"), ("radius", "radius")):
        out.append(f"pub mod {unit} {{")
        for t in data[family]["tokens"]:
            name = re.sub(rf"^{unit}-", "", t["name"])
            name = "S" + const_name(name) if name[0].isdigit() else const_name(name)
            out.append(f"    /// {t['usage']}")
            out.append(f"    pub const {name}: f32 = {f(px(t['value']))};")
        out.append("}")
        out.append("")

    out.append("pub mod duration {")
    for t in data["duration"]["tokens"]:
        name = const_name(re.sub(r"^dur-", "", t["name"]))
        out.append(f"    /// {t['usage']}")
        out.append(f"    pub const {name}_MS: u32 = {ms(t['value'])};")
    out.append("}")
    out.append("")

    out.append("pub mod shadow {")
    out.append("    use super::{ShadowLayer, ThemedShadow};")
    for t in data["shadow"]["tokens"]:
        parts = []
        for th in THEMES:
            v = t["value"] if isinstance(t["value"], str) else t["value"][th]
            layers = ", ".join(
                f"ShadowLayer {{ x: {f(x)}, y: {f(y)}, blur: {f(b)}, spread: {f(s)}, color: {c} }}"
                for x, y, b, s, c in shadow_layers(v))
            parts.append(f"{th}: &[{layers}]")
        out.append(f"    /// {t['usage']}")
        out.append(f"    pub const {const_name(re.sub(r'^shadow-', '', t['name']))}: ThemedShadow = ThemedShadow {{ {', '.join(parts)} }};")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the generated file is stale")
    args = parser.parse_args()
    text = render(json.loads(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run tools/gen_design_tokens.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
